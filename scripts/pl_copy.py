def get_pl_copy(key: str, r=None, lists=None, neighbors=None):
    folded = (key or "").replace("-", " ").strip()
    hand = COPY.get(key) or COPY.get(folded)
    if not hand and r:
        for cand in (
            (r.get("name") or "").lower(),
            (r.get("web_name") or "").lower(),
            folded.split()[-1] if folded else "",
        ):
            cand = cand.replace("-", " ").replace("'", "").replace("’", "")
            if cand in COPY:
                hand = COPY[cand]
                break
    gen_plus, gen_minus, gen_grafs = generate_take(r or {}, lists, neighbors)
    if not hand:
        return {"plus": gen_plus, "minus": gen_minus, "grafs": gen_grafs}
    plus = list(dict.fromkeys(list(hand.get("plus") or []) + gen_plus))[:5]
    minus = list(dict.fromkeys(list(hand.get("minus") or []) + gen_minus))[:5]
    grafs = list(hand.get("grafs") or [])
    if len(grafs) < 5:
        for g in gen_grafs:
            if g not in grafs:
                grafs.append(g)
            if len(grafs) >= 5:
                break
    return {"plus": plus, "minus": minus, "grafs": grafs}
