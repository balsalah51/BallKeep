def _n(v, default=0):
    try:
        if v in (None, "", "—"):
            return default
        return float(v)
    except (TypeError, ValueError):
        return default


def _i(v, default=0):
    return int(round(_n(v, default)))


def _club(r):
    return r.get("team_name") or r.get("team") or "his club"


def _pos_word(r):
    return {
        "FWD": "forward",
        "MID": "midfielder",
        "DEF": "defender",
        "GKP": "goalkeeper",
    }.get(r.get("pos") or "", "player")


def _ord(n):
    try:
        n = int(n)
    except (TypeError, ValueError):
        return str(n)
    if 10 <= n % 100 <= 20:
        suf = "th"
    else:
        suf = {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suf}"


def _money(r):
    p = r.get("price")
    if p in (None, ""):
        return ""
    return f"£{p}m"


def _set_pieces(r):
    bits = []
    if r.get("pens") == 1:
        bits.append("first-choice penalties")
    elif r.get("pens"):
        bits.append(f"penalty order #{_i(r.get('pens'))}")
    if r.get("corners") == 1:
        bits.append("first-choice corners")
    elif r.get("corners"):
        bits.append(f"corners order #{_i(r.get('corners'))}")
    if r.get("dfk") == 1:
        bits.append("first-choice direct free-kicks")
    elif r.get("dfk"):
        bits.append(f"direct free-kick order #{_i(r.get('dfk'))}")
    return bits


def _hi_lo(ranks):
    if not ranks:
        return None, None, None, None
    items = sorted(ranks.items(), key=lambda kv: kv[1])
    return items[0][0], items[0][1], items[-1][0], items[-1][1]


def _status_line(r):
    news = (r.get("news") or "").strip()
    status = r.get("status") or "a"
    label = {"d": "doubtful", "i": "injured", "s": "suspended", "u": "unavailable", "n": "not in the squad"}.get(status, "")
    bits = []
    if label:
        bits.append(label)
    if news:
        bits.append(news.rstrip("."))
    if r.get("chance") not in (None, ""):
        bits.append(f"{r['chance']}% chance of playing")
    return "; ".join(bits)


